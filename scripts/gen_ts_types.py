#!/usr/bin/env python3
"""Generate TypeScript declarations from the harness tool-payload JSON Schema.

Why this exists
---------------
The tool payload contract lives in one place: ``src/deepseek_harness/tools.py``
(``_TOOL_SCHEMAS``), mirrored by ``schemas/harness_tools.schema.json``. Hand-written
``.d.ts`` files drift into a second, silently different contract — exactly the class
of failure the HF discussion ``deepseek-ai/DeepSeek-V4.1-Flash#46`` documented for
model-written memory (161 KB of restated prose versus 13 KB of facts): restating the
same information by hand buys nothing and rots. So the TypeScript side is generated,
and the checked-in artifact is verified in CI by ``--check``.

Usage
-----
    python scripts/gen_ts_types.py                  # regenerate types/harness_types.d.ts
    python scripts/gen_ts_types.py --check          # exit 1 if the artifact is stale
    python scripts/gen_ts_types.py --schema S --out O

Stdlib only; output is byte-deterministic (definitions sorted by name, properties in
schema order, LF endings, trailing newline), so a second run is a no-op.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCHEMA = ROOT / "schemas" / "harness_tools.schema.json"
DEFAULT_OUT = ROOT / "types" / "harness_types.d.ts"

HEADER = """\
// AUTO-GENERATED FILE — DO NOT EDIT.
// Generated by scripts/gen_ts_types.py from schemas/harness_tools.schema.json
// (JSON Schema draft 2020-12). Field names mirror src/deepseek_harness/tools.py
// _TOOL_SCHEMAS; writer-side contracts, not prompt requests — see HF discussion
// deepseek-ai/DeepSeek-V4.1-Flash#46 for why that distinction matters.
//
// Regenerate: python scripts/gen_ts_types.py
// Verify:     python scripts/gen_ts_types.py --check
"""

_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_STRING_TYPES = {
    "string": "string",
    "number": "number",
    "integer": "number",
    "boolean": "boolean",
    "null": "null",
}


def _ref_name(ref: str) -> str:
    """``#/$defs/PlanStep`` -> ``PlanStep``."""
    if not ref.startswith("#/"):
        raise ValueError(f"unsupported $ref (only local refs are supported): {ref}")
    return ref.rsplit("/", 1)[-1]


def _property_key(name: str) -> str:
    return name if _IDENTIFIER.match(name) else json.dumps(name, ensure_ascii=False)


def _jsdoc(node: dict[str, Any], indent: str = "") -> list[str]:
    text = node.get("description") or node.get("title")
    if not text:
        return []
    single = " ".join(str(text).split())
    return [f"{indent}/** {single} */"]


def ts_type(node: dict[str, Any]) -> str:
    """Render a JSON Schema node as a TypeScript type expression."""
    if "$ref" in node:
        return _ref_name(node["$ref"])

    if "enum" in node:
        values = node["enum"]
        if not values:
            return "never"
        return " | ".join(
            json.dumps(value, ensure_ascii=False) if isinstance(value, str) else json.dumps(value)
            for value in values
        )

    for combinator in ("oneOf", "anyOf"):
        if combinator in node:
            return " | ".join(ts_type(branch) for branch in node[combinator])

    declared = node.get("type")
    if isinstance(declared, list):
        return " | ".join(ts_type({**{k: v for k, v in node.items() if k != "type"}, "type": entry}) for entry in declared)

    if declared == "array":
        items = node.get("items", {})
        inner = ts_type(items)
        return f"({inner})[]" if " | " in inner and not inner.startswith("Record<") else f"{inner}[]"

    if declared == "object" or "properties" in node:
        properties = node.get("properties")
        if properties:
            # Inline object (no named $defs entry): keep it structural but readable.
            fields = "; ".join(
                f"{_property_key(name)}{'' if name in node.get('required', []) else '?'}: {ts_type(spec)}"
                for name, spec in properties.items()
            )
            return "{ " + fields + " }"
        additional = node.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {ts_type(additional)}>"
        return "Record<string, unknown>"

    if declared in _STRING_TYPES:
        # format: date-time is still a string on the wire.
        return _STRING_TYPES[declared]

    return "unknown"


def _render_interface(name: str, node: dict[str, Any]) -> list[str]:
    properties: dict[str, Any] = node.get("properties") or {}
    required = set(node.get("required") or [])
    lines = _jsdoc(node)
    lines.append(f"export interface {name} {{")
    for prop_name, spec in properties.items():
        lines.extend(_jsdoc(spec, indent="  "))
        optional = "" if prop_name in required else "?"
        lines.append(f"  {_property_key(prop_name)}{optional}: {ts_type(spec)};")
    lines.append("}")
    return lines


def _render_alias(name: str, node: dict[str, Any]) -> list[str]:
    lines = _jsdoc(node)
    lines.append(f"export type {name} = {ts_type(node)};")
    return lines


def generate(schema: dict[str, Any]) -> str:
    """Return the full ``.d.ts`` text for ``schema`` (deterministic)."""
    defs = schema.get("$defs")
    if not isinstance(defs, dict) or not defs:
        raise ValueError('schema must declare named types under "$defs"')

    blocks: list[str] = [HEADER.rstrip("\n")]
    for name in sorted(defs):
        node = defs[name]
        if not isinstance(node, dict):
            raise ValueError(f"$defs.{name} must be an object")
        if "enum" in node:
            blocks.append("\n".join(_render_alias(name, node)))
        elif node.get("type") == "object" or "properties" in node:
            blocks.append("\n".join(_render_interface(name, node)))
        else:
            blocks.append("\n".join(_render_alias(name, node)))

    return "\n\n".join(blocks) + "\n"


def _read_schema(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"schema root must be an object: {path}")
    return data


def main(argv: list[str] | None = None) -> int:
    """CLI entry point. Returns the process exit code (0 ok / 1 stale / 2 error)."""
    parser = argparse.ArgumentParser(description="Generate TypeScript types from a JSON Schema.")
    parser.add_argument("--schema", default=str(DEFAULT_SCHEMA), help="input JSON Schema")
    parser.add_argument("--out", default=str(DEFAULT_OUT), help="output .d.ts path")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the artifact is missing or differs from fresh output",
    )
    args = parser.parse_args(argv)

    schema_path = Path(args.schema)
    out_path = Path(args.out)

    try:
        expected = generate(_read_schema(schema_path))
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if args.check:
        try:
            actual = out_path.read_text(encoding="utf-8")
        except OSError:
            print(f"stale: {out_path} is missing; run python scripts/gen_ts_types.py", file=sys.stderr)
            return 1
        if actual != expected:
            print(f"stale: {out_path} differs from the schema; run python scripts/gen_ts_types.py", file=sys.stderr)
            return 1
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
